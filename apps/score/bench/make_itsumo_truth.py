#!/usr/bin/env python3
"""「いつも何度でも(初級)」1ページ目の正解データを作る。
   出典: なつみの楽譜写真(samples/itsumo_p1.png)を目視で採譜(08-08)。
   3/4拍子・ヘ長調(♭1)・24小節。m20→m21のF4はタイだが、両方を別の音として数える
   (タイを読めないエンジン同士を同じ土俵で比べるため)。"""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))

NOTE = {'C':0,'D':2,'E':4,'F':5,'G':7,'A':9,'B':11}
def m(name):  # "F4" -> midi, "Bb3" -> flat
    step = NOTE[name[0]]; i = 1; alt = 0
    if name[i] == 'b': alt = -1; i += 1
    if name[i] == '#': alt = 1; i += 1
    return (int(name[i:]) + 1) * 12 + step + alt

# 各小節 = (右手のイベント列, 左手のイベント列)。イベント = (音名 or None=休符, 拍)
M = [
    ([(None,1),('F4',1),('A4',1)],            [('F3',3)]),                       # 1
    ([(None,1),('F4',1),('A4',1)],            [('F3',3)]),                       # 2
    ([(None,1),('F4',1),('A4',1)],            [('F3',3)]),                       # 3
    ([(None,1),('F4',1),('F4',.5),('G4',.5)], [('F3',1),(None,1),('A3',1)]),     # 4
    ([('A4',.5),('F4',.5),('C5',1.5),('A4',.5)], [('F3',1),('A3',1),('C4',1)]),  # 5
    ([('G4',1),('C5',1),('G4',1)],            [('C3',1),('E3',1),('G3',1)]),     # 6
    ([('F4',.5),('D4',.5),('A4',1.5),('F4',.5)], [('D3',1),('F3',1),('A3',1)]),  # 7
    ([('E4',2),('E4',1)],                     [('A2',1),('E3',1),('C4',1)]),     # 8
    ([('D4',1),('E4',1),('F4',.5),('G4',.5)], [('Bb2',1),('F3',1),('Bb3',1)]),   # 9
    ([('C4',1),('F4',1),('G4',.5),('A4',.5)], [('A2',1),('F3',1),('C4',1)]),     # 10
    ([('Bb4',1),('Bb4',.5),('A4',.5),('G4',.5),('F4',.5)], [('G2',1),('D3',1),('Bb3',1)]), # 11
    ([('G4',2),('F4',.5),('G4',.5)],          [('C3',1),('G3',1),('Bb3',1)]),    # 12
    ([('A4',.5),('F4',.5),('C5',1.5),('A4',.5)], [('F3',1),('C4',1),('F4',1)]),  # 13
    ([('G4',1),('C5',1),('G4',1)],            [('C3',1),('G3',1),('C4',1)]),     # 14
    ([('F4',.5),('D4',.5),('D4',1),('E4',.5),('F4',.5)], [('D3',1),('A3',1),('D4',1)]), # 15
    ([('C4',2),(None,.5),('A4',.5)],          [('A2',1),('E3',2)]),              # 16
    ([('D4',1),('E4',1),('F4',.5),('G4',.5)], [('Bb2',1),('F3',1),('Bb3',1)]),   # 17
    ([('C4',1),('F4',1),('G4',.5),('A4',.5)], [('A2',1),('F3',1),('C4',1)]),     # 18
    ([('Bb4',1),('Bb4',.5),('A4',.5),('G4',.5),('F4',.5)], [('G3',2),('G3',1)]), # 19
    ([('F4',3)],                              [('F2',1),('C3',1),('A3',1)]),     # 20
    ([('F4',2),('A4',.5),('Bb4',.5)],         [('F2',1),('C3',1),('A3',1)]),     # 21
    ([('C5',1),('C5',1),('C5',1)],            [('F2',1),('C3',1),('A3',1)]),     # 22
    ([('C5',1),('C5',.5),('D5',.5),('C5',.5),('Bb4',.5)], [('C3',1),('G3',1),('Bb3',1)]), # 23
    ([('A4',1),('A4',1),('A4',1)],            [('D3',1),('F3',1),('A3',1)]),     # 24
]

pitches, pds, onsets = [], [], []
for mi, (rh, lh) in enumerate(M):
    for hand in (rh, lh):
        t = mi * 3.0
        total = 0
        for name, q in hand:
            if name is not None:
                midi = m(name)
                pitches.append(midi)
                pds.append(f"{midi}/{q:g}")
                onsets.append(f"{midi}@{t:.2f}")
            t += q; total += q
        assert abs(total - 3.0) < 1e-6, f"m{mi+1} {hand} sums to {total}"

json.dump(pitches, open(os.path.join(HERE,'itsumo_truth.json'),'w'))
json.dump(pds, open(os.path.join(HERE,'itsumo_truthpd.json'),'w'))
json.dump(onsets, open(os.path.join(HERE,'itsumo_truthtime.json'),'w'))
print(f"音数 {len(pitches)}  (右手+左手, 24小節)")
